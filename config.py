def load_chats(file_path='chats.txt'):
    """Читает список чатов из файла, игнорируя пустые строки."""
    if not os.path.exists(file_path):
        print(f"⚠️ Файл {file_path} не найден! Бот не знает, какие чаты мониторить.")
        return []
    with open(file_path, 'r', encoding='utf-8') as f:
        # Читаем строки, убираем пробелы по краям и фильтруем пустые строки
        return [line.strip() for line in f if line.strip()]

